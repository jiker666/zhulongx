from __future__ import annotations

from app.agent_engine.tools.builtin.candidate import SubmitCandidateExecutor
from app.agent_engine.tools.builtin.archive import ExtractArchiveExecutor
from app.agent_engine.tools.builtin.filesystem import GrepExecutor, ListDirExecutor, ReadFileExecutor, WriteFileExecutor
from app.agent_engine.tools.builtin.http import HttpRequestExecutor
from app.agent_engine.tools.builtin.human import AskHumanExecutor
from app.agent_engine.tools.builtin.process import RunPythonExecutor, RunShellExecutor
from app.agent_engine.tools.builtin.skill import LoadSkillExecutor
from app.agent_engine.tools.builtin.state_updates import StateUpdateExecutor
from app.agent_engine.tools.builtin.worker import worker_definitions
from app.agent_engine.events import EventType
from app.agent_engine.tools.registry import ToolRegistry
from app.agent_engine.tools.types import ToolDefinition
from app.agent_engine.skills.loader import SkillLoader


def build_builtin_registry(
    skill_loader: SkillLoader | None = None,
    *,
    http_executor: HttpRequestExecutor | None = None,
) -> ToolRegistry:
    registry = ToolRegistry()
    definitions = (
        ToolDefinition(
            name="list_dir",
            description="List files and directories inside the run workspace.",
            input_schema={
                "type": "object",
                "properties": {"path": {"type": "string", "maxLength": 4096}},
                "additionalProperties": False,
            },
            risk_level="low",
            permissions=("local_read",),
            timeout_seconds=5,
            executor=ListDirExecutor(),
            idempotency="read_only",
            side_effect_level="read",
            parallel_safe=True,
            evidence_type="file_inventory",
        ),
        ToolDefinition(
            name="read_file",
            description="Read a bounded byte range from a workspace file.",
            input_schema={
                "type": "object",
                "properties": {
                    "path": {"type": "string", "minLength": 1, "maxLength": 4096},
                    "offset": {"type": "integer", "minimum": 0},
                    "limit": {"type": "integer", "minimum": 1, "maximum": 200000},
                },
                "required": ["path"],
                "additionalProperties": False,
            },
            risk_level="low",
            permissions=("local_read",),
            timeout_seconds=10,
            executor=ReadFileExecutor(),
            idempotency="read_only",
            side_effect_level="read",
            parallel_safe=True,
            evidence_type="file_content",
        ),
        ToolDefinition(
            name="write_file",
            description="Write a text file inside the writable run workspace.",
            input_schema={
                "type": "object",
                "properties": {
                    "path": {"type": "string", "minLength": 1, "maxLength": 4096},
                    "content": {"type": "string", "maxLength": 1000000},
                },
                "required": ["path", "content"],
                "additionalProperties": False,
            },
            risk_level="medium",
            permissions=("local_write",),
            timeout_seconds=10,
            executor=WriteFileExecutor(),
            idempotency="idempotent",
            side_effect_level="write",
            resource_locks=("workspace_write",),
            evidence_type="derived_file",
        ),
        ToolDefinition(
            name="grep",
            description="Search workspace text files with a regular expression.",
            input_schema={
                "type": "object",
                "properties": {
                    "pattern": {"type": "string", "minLength": 1, "maxLength": 1000},
                    "path": {"type": "string", "maxLength": 4096},
                    "max_results": {"type": "integer", "minimum": 1, "maximum": 200},
                },
                "required": ["pattern"],
                "additionalProperties": False,
            },
            risk_level="low",
            permissions=("local_read",),
            timeout_seconds=15,
            executor=GrepExecutor(),
            idempotency="read_only",
            side_effect_level="read",
            parallel_safe=True,
            evidence_type="search_result",
        ),
        ToolDefinition(
            name="run_shell",
            description="Run a shell command in the configured sandbox workspace.",
            input_schema={
                "type": "object",
                "properties": {
                    "command": {"type": "string", "minLength": 1, "maxLength": 20000},
                    "timeout_seconds": {"type": "number", "minimum": 0.1, "maximum": 30},
                },
                "required": ["command"],
                "additionalProperties": False,
            },
            risk_level="high",
            permissions=("process_execution",),
            timeout_seconds=30,
            executor=RunShellExecutor(),
            idempotency="non_idempotent",
            side_effect_level="execute",
            resource_locks=("sandbox_process", "workspace_write"),
            evidence_type="command_output",
        ),
        ToolDefinition(
            name="run_python",
            description="Run Python code in the configured sandbox workspace.",
            input_schema={
                "type": "object",
                "properties": {
                    "code": {"type": "string", "minLength": 1, "maxLength": 200000},
                    "timeout_seconds": {"type": "number", "minimum": 0.1, "maximum": 30},
                },
                "required": ["code"],
                "additionalProperties": False,
            },
            risk_level="high",
            permissions=("process_execution",),
            timeout_seconds=30,
            executor=RunPythonExecutor(),
            idempotency="non_idempotent",
            side_effect_level="execute",
            resource_locks=("sandbox_process", "workspace_write"),
            evidence_type="command_output",
        ),
        ToolDefinition(
            name="submit_candidate",
            description="Submit a candidate result with evidence event references for validation.",
            input_schema={
                "type": "object",
                "properties": {
                    "candidate": {"type": "string", "minLength": 1, "maxLength": 4096},
                    "evidence_event_ids": {"type": "array", "items": {"type": "string"}},
                    "reproduction": {"type": "string", "maxLength": 20000},
                },
                "required": ["candidate"],
                "additionalProperties": False,
            },
            risk_level="low",
            permissions=("candidate_submit",),
            timeout_seconds=5,
            executor=SubmitCandidateExecutor(),
            idempotency="idempotent",
            side_effect_level="state",
            resource_locks=("candidate_state",),
            evidence_type="candidate",
        ),
        ToolDefinition(
            name="extract_archive",
            description="Extract ZIP or TAR members inside the workspace with traversal and link checks.",
            input_schema={
                "type": "object",
                "properties": {"path": {"type": "string", "minLength": 1, "maxLength": 4096}},
                "required": ["path"],
                "additionalProperties": False,
            },
            risk_level="medium",
            permissions=("local_read", "local_write"),
            timeout_seconds=30,
            executor=ExtractArchiveExecutor(),
            idempotency="idempotent",
            side_effect_level="write",
            resource_locks=("workspace_write",),
            evidence_type="artifact_inventory",
        ),
        ToolDefinition(
            name="http_request",
            description="Send one non-redirecting HTTP request to an explicitly authorized allowlisted target.",
            input_schema={
                "type": "object",
                "properties": {
                    "url": {"type": "string", "minLength": 1, "maxLength": 8192},
                    "method": {"type": "string", "enum": ["GET", "POST", "PUT", "PATCH", "DELETE", "HEAD"]},
                    "headers": {"type": "object"},
                    "body": {"type": "string", "maxLength": 1000000},
                    "timeout_seconds": {"type": "number", "minimum": 0.1, "maximum": 20},
                },
                "required": ["url"],
                "additionalProperties": False,
            },
            risk_level="high",
            permissions=("network_access",),
            timeout_seconds=20,
            executor=http_executor or HttpRequestExecutor(),
            idempotency="non_idempotent",
            side_effect_level="network",
            resource_locks=("network",),
            requires_approval=True,
            evidence_type="network_response",
        ),
        ToolDefinition(
            name="ask_human",
            description="Pause the run and request a specific human decision or missing input.",
            input_schema={
                "type": "object",
                "properties": {"question": {"type": "string", "minLength": 1, "maxLength": 10000}},
                "required": ["question"],
                "additionalProperties": False,
            },
            risk_level="low",
            permissions=(),
            timeout_seconds=5,
            executor=AskHumanExecutor(),
            idempotency="idempotent",
            side_effect_level="state",
            resource_locks=("human_gate",),
            evidence_type="human_input",
        ),
        ToolDefinition(
            name="record_evidence",
            description="Record a typed evidence item backed by source event IDs.",
            input_schema={
                "type": "object",
                "properties": {
                    "evidence_id": {"type": "string", "minLength": 1},
                    "evidence_type": {"type": "string", "minLength": 1},
                    "summary": {"type": "string", "minLength": 1, "maxLength": 20000},
                    "source_event_ids": {"type": "array", "items": {"type": "string"}},
                    "artifact_id": {"type": "string"},
                    "locator": {"type": "string"},
                    "confidence": {"type": "number", "minimum": 0, "maximum": 1},
                },
                "required": ["evidence_id", "evidence_type", "summary", "source_event_ids"],
                "additionalProperties": False,
            },
            risk_level="low",
            permissions=("state_update",),
            timeout_seconds=5,
            executor=StateUpdateExecutor(EventType.EVIDENCE_RECORDED, "evidence"),
            idempotency="idempotent",
            side_effect_level="state",
            resource_locks=("decision_state",),
            evidence_type="evidence_record",
        ),
        ToolDefinition(
            name="record_fact",
            description="Confirm one fact with evidence references and confidence.",
            input_schema={
                "type": "object",
                "properties": {
                    "fact_id": {"type": "string", "minLength": 1},
                    "statement": {"type": "string", "minLength": 1, "maxLength": 20000},
                    "evidence_ids": {"type": "array", "items": {"type": "string"}},
                    "confidence": {"type": "number", "minimum": 0, "maximum": 1},
                    "source": {"type": "string", "minLength": 1},
                },
                "required": ["fact_id", "statement", "evidence_ids", "confidence", "source"],
                "additionalProperties": False,
            },
            risk_level="low",
            permissions=("state_update",),
            timeout_seconds=5,
            executor=StateUpdateExecutor(EventType.FACT_CONFIRMED, "fact"),
            idempotency="idempotent",
            side_effect_level="state",
            resource_locks=("decision_state",),
            evidence_type="fact_record",
        ),
        ToolDefinition(
            name="record_hypothesis",
            description="Add an open hypothesis with a test strategy and success signal.",
            input_schema={
                "type": "object",
                "properties": {
                    "hypothesis_id": {"type": "string", "minLength": 1},
                    "statement": {"type": "string", "minLength": 1, "maxLength": 20000},
                    "test_strategy": {"type": "string", "minLength": 1, "maxLength": 20000},
                    "success_signal": {"type": "string", "minLength": 1, "maxLength": 10000},
                    "priority": {"type": "integer"},
                },
                "required": ["hypothesis_id", "statement", "test_strategy", "success_signal"],
                "additionalProperties": False,
            },
            risk_level="low",
            permissions=("state_update",),
            timeout_seconds=5,
            executor=StateUpdateExecutor(EventType.HYPOTHESIS_PROPOSED, "hypothesis"),
            idempotency="idempotent",
            side_effect_level="state",
            resource_locks=("decision_state",),
            evidence_type="hypothesis_record",
        ),
        ToolDefinition(
            name="refute_hypothesis",
            description="Refute an existing hypothesis with evidence and a reason.",
            input_schema={
                "type": "object",
                "properties": {
                    "hypothesis_id": {"type": "string", "minLength": 1},
                    "statement": {"type": "string", "minLength": 1},
                    "reason": {"type": "string", "minLength": 1},
                    "evidence_ids": {"type": "array", "items": {"type": "string"}},
                },
                "required": ["hypothesis_id", "statement", "reason", "evidence_ids"],
                "additionalProperties": False,
            },
            risk_level="low",
            permissions=("state_update",),
            timeout_seconds=5,
            executor=StateUpdateExecutor(EventType.HYPOTHESIS_REFUTED, "hypothesis"),
            idempotency="idempotent",
            side_effect_level="state",
            resource_locks=("decision_state",),
            evidence_type="hypothesis_record",
        ),
        ToolDefinition(
            name="revise_plan",
            description="Replace the active plan with a higher version and an explicit revision reason.",
            input_schema={
                "type": "object",
                "properties": {
                    "plan_id": {"type": "string", "minLength": 1},
                    "version": {"type": "integer", "minimum": 2},
                    "goal": {"type": "string", "minLength": 1},
                    "nodes": {"type": "array", "items": {"type": "object"}},
                    "alternatives": {"type": "array", "items": {"type": "string"}},
                    "risks": {"type": "array", "items": {"type": "string"}},
                    "assumptions": {"type": "array", "items": {"type": "string"}},
                    "unknowns": {"type": "array", "items": {"type": "string"}},
                    "critical_path": {"type": "array", "items": {"type": "string"}},
                    "rationale": {"type": "string"},
                    "revision_reason": {"type": "string", "minLength": 1},
                },
                "required": ["plan_id", "version", "goal", "nodes", "revision_reason"],
                "additionalProperties": False,
            },
            risk_level="low",
            permissions=("plan_update",),
            timeout_seconds=5,
            executor=StateUpdateExecutor(EventType.PLAN_REVISED, "plan"),
            idempotency="idempotent",
            side_effect_level="state",
            resource_locks=("decision_state",),
            evidence_type="plan_revision",
        ),
    )
    definitions = (*definitions, *worker_definitions())
    for definition in definitions:
        registry.register(definition)
    if skill_loader is not None:
        registry.register(ToolDefinition(
            name="load_skill",
            description="Load the full body of one indexed skill on demand.",
            input_schema={
                "type": "object",
                "properties": {"name": {"type": "string", "minLength": 1, "maxLength": 100}},
                "required": ["name"],
                "additionalProperties": False,
            },
            risk_level="low",
            permissions=("local_read",),
            timeout_seconds=5,
            executor=LoadSkillExecutor(skill_loader),
            idempotency="read_only",
            side_effect_level="read",
            parallel_safe=True,
            evidence_type="skill_context",
        ))
    return registry


__all__ = ["build_builtin_registry"]
